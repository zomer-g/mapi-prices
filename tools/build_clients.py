"""Attach client names to the sales of more than 100,000 ILS.

Reads:
  docs/sales-2022-2024.xlsx   sheet 'מעל 100,000 ש"ח' (34 sales, no client)
  docs/big-deals-clients.xlsx the same sales with the client name (column G)
Writes:
  data/big_deals.csv  one row per sale with the client and the client type
  data/clients.js     window.CLIENTS, loaded by index.html

Every sale is matched to data/sales_by_month.csv (SKU, year, month, amount) so the site
can show it in the product log instead of in the aggregated sales rows.
A sale that is in the sales file but not in the client report keeps an empty client.

Run: python3 tools/build_clients.py
"""
import csv
import json
import os

import openpyxl

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# client name as written in the report -> (type, full name, note)
# gov = government ministry or unit; pub = other public body; prv = private body
CLIENTS = {
    'משרד הביטחון': ('gov', 'משרד הביטחון', ''),
    'משרד רוה"מ': ('gov', 'משרד ראש הממשלה', ''),
    'משטרת ישראל': ('gov', 'משטרת ישראל', ''),
    'רמ"י': ('gov', 'רשות מקרקעי ישראל', ''),
    'מפ"י - החלטות ממשלה': ('gov', 'מפ"י - החלטות ממשלה', 'חיוב פנימי: עבודות שמפ"י ביצעה לפי החלטות ממשלה'),
    'UKHO': ('pub', 'UKHO - משרד ההידרוגרפיה הבריטי', 'גוף ממשלתי זר (בריטניה)'),
    'חברת חשמל': ('pub', 'חברת החשמל לישראל', 'חברה ממשלתית'),
    'א. קרשין מודדים מהנדסים בע"מ': ('prv', 'א. קרשין מודדים מהנדסים בע"מ', ''),
    'IBC': ('prv', 'IBC', 'חברת תשתית סיבים אופטיים'),
}
TYPES = {'gov': 'גוף ממשלתי', 'pub': 'גוף ציבורי אחר', 'prv': 'גוף פרטי', 'unk': 'לא צוין בדוח'}


def rows(path, sheet=None):
    wb = openpyxl.load_workbook(path, read_only=True, data_only=True)
    ws = wb[sheet] if sheet else wb.worksheets[0]
    return [r for r in ws.iter_rows(min_row=2, values_only=True) if r and r[0]]


sales = rows(os.path.join(ROOT, 'docs', 'sales-2022-2024.xlsx'), 'מעל 100,000 ש"ח')
named = {str(r[0]).strip(): (r[6] or '').strip() for r in rows(os.path.join(ROOT, 'docs', 'big-deals-clients.xlsx'))}

agg = {}
with open(os.path.join(ROOT, 'data', 'sales_by_month.csv'), encoding='utf-8-sig') as f:
    for r in csv.DictReader(f):
        agg.setdefault((r['mat'], int(r['year']), int(r['month'])), []).append(float(r['amount_ils']))

out = []
for doc, mat, desc, month, amount, year in (r[:6] for r in sales):
    doc, mat, month, year, amount = str(doc).strip(), str(mat).strip(), int(month), int(year), round(float(amount), 2)
    assert any(abs(a - amount) < 0.005 for a in agg.get((mat, year, month), [])), (doc, mat, year, month, amount)
    name = named.get(doc, '')
    if name and name not in CLIENTS:
        raise SystemExit(f'unclassified client: {name} (document {doc}); add it to CLIENTS')
    t, full, note = CLIENTS.get(name, ('unk', '', ''))
    out.append({'doc': doc, 'mat': int(mat), 'desc': desc.strip(), 'year': year, 'month': month, 'amount_ils': amount,
                'client': name, 'client_full': full, 'client_type': t, 'client_type_he': TYPES[t], 'note': note})
out.sort(key=lambda d: (d['year'], d['month'], d['doc']))

with open(os.path.join(ROOT, 'data', 'big_deals.csv'), 'w', encoding='utf-8-sig', newline='') as f:
    w = csv.DictWriter(f, fieldnames=list(out[0]))
    w.writeheader()
    w.writerows(out)

js = {'types': TYPES,
      'deals': [{'doc': d['doc'], 'm': d['mat'], 'd': d['desc'], 'ym': (d['year'] - 2000) * 100 + d['month'], 'a': d['amount_ils'],
                 'c': d['client'], 'cf': d['client_full'], 't': d['client_type'], 'n': d['note']} for d in out]}
with open(os.path.join(ROOT, 'data', 'clients.js'), 'w', encoding='utf-8') as f:
    f.write('// generated by tools/build_clients.py\nwindow.CLIENTS=' + json.dumps(js, ensure_ascii=False) + ';\n')

missing = [d['doc'] for d in out if not d['client']]
print(f'{len(out)} sales, {len(out) - len(missing)} with a client; without: {", ".join(missing) or "none"}')
